"""
Задача 3: Решение конкретной системы линейных уравнений матричным способом
"""

import numpy as np


def solve_specific_system():
    """
    Решение системы:
    -2x₁ - 8.5x₂ - 3.4x₃ + 3.5x₄ = -1.88
    2.4x₂ + 8.2x₄ = -3.28
    2.5x₁ + 1.6x₂ + 2.1x₃ + 3x₄ = -0.5
    0.3x₁ - 0.4x₂ - 4.8x₃ + 4.6x₄ = -2.83
    """

    print("Решение системы линейных уравнений матричным способом")
    print("=" * 50)
    print("Система уравнений:")
    print("-2x₁ - 8.5x₂ - 3.4x₃ + 3.5x₄ = -1.88")
    print("2.4x₂ + 8.2x₄ = -3.28")
    print("2.5x₁ + 1.6x₂ + 2.1x₃ + 3x₄ = -0.5")
    print("0.3x₁ - 0.4x₂ - 4.8x₃ + 4.6x₄ = -2.83")

    A = np.array([
        [-2.0, -8.5, -3.4, 3.5],
        [0.0, 2.4, 0.0, 8.2],
        [2.5, 1.6, 2.1, 3.0],
        [0.3, -0.4, -4.8, 4.6]
    ])

    B = np.array([-1.88, -3.28, -0.5, -2.83])

    # Находим обратную матрицу
    A_inv = np.linalg.inv(A)

    #  X = A⁻¹ * B
    X = np.dot(A_inv, B)

    print("\n" + "=" * 50)
    print("РЕЗУЛЬТАТ:")
    print("Вектор решения X (округленный до 1 знака после запятой):")
    for i, x in enumerate(X, 1):
        print(f"x{i} = {x:.1f}")


if __name__ == "__main__":
    solve_specific_system()